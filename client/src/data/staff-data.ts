// Helper function to get Discord avatar URL
export function getDiscordAvatarUrl(discordId: string, avatar: string | null): string {
  if (!avatar) {
    const defaultAvatarIndex = (parseInt(discordId.slice(-2)) || 0) % 5;
    return `https://cdn.discordapp.com/embed/avatars/${defaultAvatarIndex}.png`;
  }
  // Handle both animated (gif) and static (png/webp) avatars
  const extension = avatar.startsWith('a_') ? 'gif' : 'png';
  return `https://cdn.discordapp.com/avatars/${discordId}/${avatar}.${extension}?size=256`;
}


// Helper function to organize staff by role with hierarchy
export function getStaffByRole(staffMembers: StaffMember[]): Record<string, StaffMember[]> {
  const staffByRole: Record<string, StaffMember[]> = {
    'Founder': [],
    'Owner': [],
    'Co Owner': [],
    'Main Admin': [],
    'Developer': [],
    'Admin': [],
    'Manager': [],
    'Trial Admin': [],
    'Moderator': [],
    'Helper': [],
    'Staff+': [],
    'Staff': [],
    'FxG Family': [],
  };

  staffMembers.forEach(member => {
    const roles = member.roles || [];
    let highestRole = 'Staff'; // Default role

    // Determine highest role based on hierarchy
    if (roles.includes('Founder')) highestRole = 'Founder';
    else if (roles.includes('Owner')) highestRole = 'Owner';
    else if (roles.includes('Co Owner')) highestRole = 'Co Owner';
    else if (roles.includes('Main Admin')) highestRole = 'Main Admin';
    else if (roles.includes('Developer')) highestRole = 'Developer';
    else if (roles.includes('Admin')) highestRole = 'Admin';
    else if (roles.includes('Manager')) highestRole = 'Manager';
    else if (roles.includes('Trial Admin')) highestRole = 'Trial Admin';
    else if (roles.includes('Moderator')) highestRole = 'Moderator';
    else if (roles.includes('Helper')) highestRole = 'Helper';
    else if (roles.includes('Staff+')) highestRole = 'Staff+';
    else if (roles.includes('FxG Family')) highestRole = 'FxG Family'; // Added for new role mapping


    staffByRole[highestRole].push(member);
  });

  return staffByRole;
}